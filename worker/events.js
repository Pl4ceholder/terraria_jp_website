/**
 * これからのイベントを、始まる順に引く。
 *
 *   ?1 …… いまの時刻（ISO 8601）
 *   ?2 …… 「終わりが無いイベント」を出しておく猶予の境目（いま − 猶予）
 *   ?3 …… 一度に出す上限
 *
 * 終わりが決まっているイベントは、終わるまでは出し続ける。長く続くイベント
 * （例: 10/26 に始まって 10/29 に終わる）が、開催中なのに「始まってからの時間」で
 * 消えてしまわないようにするため。
 *
 * 終わりが無いイベント（ボイスで終わりを決めずに立てたもの）は、始まってしばらく
 * 経ったら出さない。Bot が止まっても、いつまでも残って見えないようにするため。
 */
export const EVENT_LIST_SQL = `
    SELECT id, name, description, location, cover_url, url, user_count, start_at, end_at
      FROM events
     WHERE (end_at IS NOT NULL AND end_at >= ?1)
        OR (end_at IS NULL AND start_at >= ?2)
     ORDER BY start_at
     LIMIT ?3
`;
